"""Generate Magnet AXIOM material.

INTERIM: this writes one ready-to-use SQL query per artifact plus a README with
the file path and column mapping, which is what AXIOM's SQLite-based custom
artifacts are built from. Native AXIOM custom-artifact files (XML/.py) will be
generated once the exact format has been checked against a real AXIOM export;
see docs/TOOLS.md.
"""
from . import spec as specmod

TIMESTAMP_SQL = {
    'unix_s': 'datetime({c}, \'unixepoch\')',
    'unix_ms': 'datetime({c} / 1000.0, \'unixepoch\')',
    'unix_us': 'datetime({c} / 1000000.0, \'unixepoch\')',
    'unix_ns': 'datetime({c} / 1000000000.0, \'unixepoch\')',
    'apple_s': 'datetime({c} + 978307200, \'unixepoch\')',
    'apple_ns': 'datetime({c} / 1000000000.0 + 978307200, \'unixepoch\')',
    'webkit_us': 'datetime({c} / 1000000.0 - 11644473600, \'unixepoch\')',
}


def axiom_sql(art):
    """SELECT that does conversions in SQL, so AXIOM shows readable values."""
    selects = []
    for field in art['fields']:
        column = field['column']
        alias, col = column.split('.', 1) if '.' in column else ('main', column)
        expr = '%s.%s' % (specmod.quote_ident(alias), specmod.quote_ident(col))
        if field['format'] in TIMESTAMP_SQL:
            expr = 'CASE WHEN %s IS NULL OR %s = 0 THEN NULL ELSE %s END' % (
                expr, expr, TIMESTAMP_SQL[field['format']].format(c=expr))
        elif field['format'] == 'bool':
            expr = "CASE WHEN %s IS NULL THEN NULL WHEN %s THEN 'Yes' ELSE 'No' END" % (expr, expr)
        elif field['format'] == 'hex':
            expr = 'lower(hex(%s))' % expr
        elif field.get('values'):
            cases = ' '.join("WHEN '%s' THEN '%s'" % (k.replace("'", "''"), v.replace("'", "''"))
                             for k, v in field['values'].items())
            expr = 'CASE CAST(%s AS TEXT) %s ELSE %s END' % (expr, cases, expr)
        selects.append('%s AS %s' % (expr, specmod.quote_ident(field['label'])))
    base = specmod.build_sql(art)
    from_part = base[base.index('\nFROM '):]
    return 'SELECT %s%s' % (',\n       '.join(selects), from_part)


def generate(spec):
    app = spec['app']
    files = {}
    readme = ['# %s for Magnet AXIOM\n' % app['name'],
              'Generated by Project Obscure Benelux from `specs/%s/parser.yaml`.\n' % app['id'],
              'Timestamps are converted to UTC text by the queries.\n']
    for art in spec['artifacts']:
        source = spec['sources'][art['source']]
        name = '%s_%s.sql' % (app['id'], art['id'])
        files['axiom/%s/%s' % (app['id'], name)] = axiom_sql(art) + ';\n'
        readme.append('\n## %s - %s\n' % (app['name'], art['name']))
        readme.append('- Platform: %s\n- File path: `%s`\n- Query: `%s`\n- Columns:\n'
                      % (source['platform'], source['path'], name))
        for field in art['fields']:
            readme.append('  - %s (%s)\n' % (field['label'], field['format']))
    files['axiom/%s/README.md' % app['id']] = ''.join(readme)
    return files
