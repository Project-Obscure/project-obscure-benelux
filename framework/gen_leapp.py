"""Generate ALEAPP (Android) and iLEAPP (iOS) artifact modules.

Output follows the LEAPP "artifacts v2" layout: an __artifacts_v2__ header and
one @artifact_processor function per artifact. Drop the generated file into
ALEAPP/scripts/artifacts/ or iLEAPP/scripts/artifacts/.
"""
import datetime
import pprint

from . import spec as specmod

ICONS = {
    'chat': 'message-square',
    'contact': 'users',
    'account': 'user',
    'location': 'map-pin',
    'search': 'search',
    'generic': 'file-text',
}

TOOL_FOR_PLATFORM = {'android': 'aleapp', 'ios': 'ileapp'}

BODY = '''
def _obs_open(path):
    return sqlite3.connect('file:%s?mode=ro' % path.replace('\\\\', '/'), uri=True)


def _obs_cell(value):
    if value is None:
        return ''
    if isinstance(value, datetime.datetime):
        return value.replace(tzinfo=datetime.timezone.utc)
    if isinstance(value, bool):
        return 'Yes' if value else 'No'
    return value


def _obs_run(key, files_found):
    art = _OBS_ARTIFACTS[key]
    headers = []
    for field in art['fields']:
        if obs_is_timestamp(field['format']):
            headers.append((field['label'], 'datetime'))
        else:
            headers.append(field['label'])
    rows = []
    sources = []
    for file_found in files_found:
        file_found = str(file_found)
        if not fnmatch.fnmatch(os.path.basename(file_found), _OBS_DB_NAMES[key]):
            continue
        try:
            conn = _obs_open(file_found)
            try:
                cursor = conn.execute(_OBS_SQL[key])
                names = [d[0] for d in cursor.description]
                for raw in cursor:
                    shaped = obs_shape(art, dict(zip(names, raw)))
                    rows.append(tuple(_obs_cell(v) for _label, v in shaped['columns']))
            finally:
                conn.close()
            sources.append(file_found)
        except sqlite3.Error as ex:
            logfunc('Project Obscure %s: could not read %s (%s)' % (key, file_found, ex))
    return tuple(headers), rows, ', '.join(sources)
'''


def module_name(spec):
    return 'obscure_' + spec['app']['id'].replace('-', '_').replace('.', '_')


def function_name(spec, art):
    return '%s_%s' % (module_name(spec), art['id'])


def generate(spec, platform):
    """Return {relative output path: file content} for one platform, or {}."""
    arts = [a for a in spec['artifacts'] if spec['sources'][a['source']]['platform'] == platform]
    if not arts:
        return {}
    app = spec['app']
    today = datetime.date.today().isoformat()
    header = {}
    for art in arts:
        source = spec['sources'][art['source']]
        path = source['path']
        header[function_name(spec, art)] = {
            'name': '%s - %s' % (app['name'], art['name']),
            'description': art['description'] or app['description'],
            'author': app['author'],
            'creation_date': str(app.get('created', today)),
            'last_update_date': today,
            'requirements': 'none',
            'category': app['category'],
            'notes': 'Project Obscure Benelux parser %s (status: %s)' % (app['id'], app['status']),
            'paths': (path, path + '-*'),
            'output_types': 'standard',
            'artifact_icon': ICONS[art['type']],
        }
    runtime_arts = dict((a['id'], specmod.runtime_artifact(a)) for a in arts)
    sql = dict((a['id'], specmod.build_sql(a)) for a in arts)
    db_names = dict((a['id'], specmod.db_filename(spec['sources'][a['source']])) for a in arts)

    out = []
    out.append('# Generated by Project Obscure Benelux from parsers/%s/parser.yaml\n'
               '# Do not edit this file by hand: change parser.yaml and regenerate.\n' % app['id'])
    out.append('__artifacts_v2__ = %s\n' % pprint.pformat(header, indent=4, sort_dicts=False))
    out.append('import datetime\nimport fnmatch\nimport os\nimport sqlite3\n\n'
               'from scripts.ilapfuncs import artifact_processor, logfunc\n\n')
    out.append(specmod.read_template('runtime.py'))
    out.append('\n\n')
    out.append(specmod.read_template('shaper.py'))
    out.append('\n\n_OBS_ARTIFACTS = %s\n' % pprint.pformat(runtime_arts, sort_dicts=False))
    out.append('\n_OBS_SQL = %s\n' % pprint.pformat(sql, sort_dicts=False))
    out.append('\n_OBS_DB_NAMES = %s\n' % pprint.pformat(db_names, sort_dicts=False))
    out.append(BODY)
    for art in arts:
        out.append('\n\n@artifact_processor\n'
                   'def %s(files_found, report_folder, seeker, wrap_text):\n'
                   '    return _obs_run(%r, files_found)\n' % (function_name(spec, art), art['id']))
    tool = TOOL_FOR_PLATFORM[platform]
    return {'%s/scripts/artifacts/%s.py' % (tool, module_name(spec)): ''.join(out)}
